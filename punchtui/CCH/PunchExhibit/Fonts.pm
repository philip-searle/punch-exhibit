=pod
=head2 lookup_code_char

Looks up the value for I<$c> in the hash reference I<$cur_code>.
If it does not exist, it will be looked up in I<$alt_code>, along with
the value of the character used to switch character codes.

Returns a list containing:

=over

=item I<$flip>

The value of item C<FLIP> in I<$cur_code> if the alternate code was used.

=item I<$code>

The resolved value of item I<$c>.

=item I<$cur_code>

The new reference to be used for I<$cur_code> for the next call to this sub.

=item I<$alt_code>

The new reference to be used for I<$alt_code> for the next call to this sub.

=back

=cut
sub lookup_code_char {
	my ($c, $cur_code, $alt_code) = @_;
	my $code = $cur_code->{$c};
	if (defined $code) {
		return (undef, flip_bits($code), $cur_code, $alt_code);
	}
	$code = $alt_code->{$c};
	if (defined $code) {
		return (flip_bits($cur_code->{FLIP}), flip_bits($code), $alt_code, $cur_code);
	}
	return (undef, flip_bits($cur_code->{' '}), $cur_code, $alt_code);
}

sub flip_bits {
	my $b = shift;
	return (
		((($b >> 4) & 1) << 0) |
		((($b >> 3) & 1) << 1) |
		((($b >> 2) & 1) << 2) |
		((($b >> 1) & 1) << 3) |
		((($b >> 0) & 1) << 4)
	);
}

